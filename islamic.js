// ------------------------------------------------------------ تلاوة نصية: سورة أو آية
const surahCache = new Map();
async function fetchSurah(n) {
    if (surahCache.has(n)) return surahCache.get(n);
    let ayahs = null;
    try {
        const r = await axios.get(`https://api.alquran.cloud/v1/surah/${n}/quran-uthmani`, { timeout: 20000 });
        const list = r.data?.data?.ayahs;
        if (Array.isArray(list) && list.length) ayahs = list.map((a) => ({ n: a.numberInSurah, text: String(a.text) }));
    } catch (e) {}
    if (!ayahs) {
        try {
            const r = await axios.get(`https://cdn.jsdelivr.net/gh/fawazahmed0/quran-api@1/editions/ara-quranuthmanihaf/${n}.json`, { timeout: 20000 });
            const list = r.data?.chapter;
            if (Array.isArray(list) && list.length) ayahs = list.map((a) => ({ n: a.verse, text: String(a.text) }));
        } catch (e) {}
    }
    if (!ayahs) return null;
    // حذف البسملة الملصقة بأول آية (ما عدا الفاتحة والتوبة)
    if (n !== 1 && n !== 9 && ayahs[0] && normWord(ayahs[0].text).startsWith('بسم')) {
        const words = ayahs[0].text.split(' ');
        if (words.length > 4) ayahs[0] = { ...ayahs[0], text: words.slice(4).join(' ') };
    }
    surahCache.set(n, ayahs);
    return ayahs;
}

function chunkAyahs(ayahs, max = 3000) {
    const chunks = []; let cur = '';
    for (const a of ayahs) {
        const piece = `${a.text} ﴿${toArabicNum(a.n)}﴾ `;
        if (cur && (cur.length + piece.length) > max) { chunks.push(cur.trim()); cur = ''; }
        cur += piece;
    }
    if (cur.trim()) chunks.push(cur.trim());
    return chunks;
}

const SURAH_USAGE = '📖 *سورة:*\n\n> 📖 .سورة <اسم أو رقم> ↞ السورة كاملة\n> 🔹 .سورة <اسم أو رقم> <رقم الآية> ↞ آية محددة\n> 🔹 .سورة <اسم أو رقم> <من>-<إلى> ↞ مجموعة آيات\n\n💡 أمثلة: `.سورة الكهف` • `.سورة البقرة 255` • `.سورة 112` • `.سورة الملك 1-5`\n🎙️ للتلاوة الصوتية أضف اسم القارئ: `.سورة الكهف ماهر`';

async function cmdSurah(ctx, args) {
    const { sock, from, send } = ctx;
    const s = resolveSurah(args);
    if (!s) { await send(sock, from, { text: SURAH_USAGE }); return true; }
    // إن وُجد بعد اسم السورة نص غير رقمي (اسم قارئ) نتركه للتلاوة الصوتية الموجودة أصلاً
    const rest = toLatin(s.rest || '').replace(/^(?:ايه|اية|آية|الايه|الاية|الآية|ايات|آيات)\s*/i, '').trim();
    let range = null;
    if (rest) {
        const m = rest.match(/^(\d{1,3})(?:\s*[-–—~]\s*(\d{1,3})|\s+(?:الى|إلى|الي)\s+(\d{1,3}))?$/);
        if (!m) return false;
        range = [Number(m[1]), Number(m[2] || m[3] || m[1])];
        if (range[0] > range[1]) range = [range[1], range[0]];
    }
    const name = SURAHS[s.n - 1];
    const ayahs = await fetchSurah(s.n);
    if (!ayahs) { await send(sock, from, { text: '❌ تعذر جلب نص السورة حالياً، حاول بعد قليل.' }); return true; }
    if (!range) {
        const chunks = chunkAyahs(ayahs);
        const bism = (s.n !== 1 && s.n !== 9) ? 'بِسْمِ ٱللَّهِ ٱلرَّحْمَـٰنِ ٱلرَّحِيمِ\n\n' : '';
        for (let i = 0; i < chunks.length; i++) {
            const head = i === 0 ? `📖 *سُورَةُ ${name}* (${toArabicNum(ayahs.length)} آية)\n\n${bism}` : '';
            await send(sock, from, { text: head + chunks[i] });
            if (i < chunks.length - 1) await new Promise((r) => setTimeout(r, 700));
        }
        return true;
    }
    const [a, b] = range;
    if (a < 1 || b > ayahs.length) { await send(sock, from, { text: `❌ سورة ${name} فيها ${toArabicNum(ayahs.length)} آية فقط.` }); return true; }
    const sel = ayahs.filter((x) => x.n >= a && x.n <= b);
    const label = a === b ? `الآية ${toArabicNum(a)}` : `الآيات ${toArabicNum(a)} - ${toArabicNum(b)}`;
    const chunks = chunkAyahs(sel);
    for (let i = 0; i < chunks.length; i++) {
        const head = i === 0 ? `📖 *سُورَةُ ${name} • ${label}*\n\n` : '';
        await send(sock, from, { text: head + chunks[i] });
        if (i < chunks.length - 1) await new Promise((r) => setTimeout(r, 700));
    }
    return true;
}

