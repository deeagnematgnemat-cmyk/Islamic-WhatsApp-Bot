function ammanMinutesNow() {
    const t = new Date().toLocaleTimeString('en-GB', { timeZone: 'Asia/Amman', hourCycle: 'h23', hour: '2-digit', minute: '2-digit' });
    const [h, m] = t.split(':').map(Number);
    return ((h % 24) * 60) + m;
}
