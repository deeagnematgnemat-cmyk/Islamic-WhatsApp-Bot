function fmtHM(hhmm) {
    const [h, m] = hhmm.split(':').map(Number);
    const suffix = h >= 12 ? 'م' : 'ص';
    const h12 = h % 12 === 0 ? 12 : h % 12;
    return `${h12}:${String(m).padStart(2, '0')} ${suffix}`;
}
function parseTime(raw) {
    let s = toLatin(raw).toLowerCase()
        .replace(/الساع[ةه]/g, ' ').replace(/صباحا|صباحاً|صباحًا/g, 'ص').replace(/مساء|مساءً|مساءا|ظهرا|ظهراً|عصرا|ليلا|ليلاً/g, 'م')
        .replace(/\s+(ص|م|am|pm)(?=\s|$)/g, '$1').trim();
    const m = s.match(/^(\d{1,2})(?::(\d{2}))?(ص|م|am|pm)?$/i);
    if (!m) return null;
    let h = Number(m[1]); const min = m[2] ? Number(m[2]) : 0; const suf = (m[3] || '').toLowerCase();
    if (min > 59) return null;
    if (suf) { if (h < 1 || h > 12) return null; h = (suf === 'م' || suf === 'pm') ? (h % 12) + 12 : h % 12; }
    else if (h > 23) return null;
    return `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}`;
}

